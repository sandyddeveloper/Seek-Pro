const lightOverlays = Object.fromEntries(
  Object.entries(overlays).map(([name, value]) => {
    const alpha = value.match(/[\d.]+\)$/)?.[0].slice(0, -1);
    const paletteKey = name.match(/^[a-zA-Z]+/)?.[0];
    const rgb = paletteKey === 'black' ? '0, 0, 0' : lightOverlayRgb[paletteKey as keyof typeof lightOverlayRgb];

    return [name, rgb && alpha ? `rgba(${rgb}, ${alpha})` : value];
  }),
) as ThemeOverlays;

export function getThemePalette(mode: ResolvedThemeMode) {
  return mode === 'light'
    ? { colors: lightColors, overlays: lightOverlays, fontFamilies: lightFontFamilies }
    : { colors, overlays, fontFamilies };
}